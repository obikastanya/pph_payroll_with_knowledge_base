"""Result figures of the paper, built from the experiment logs without calling an LLM (PANDUAN Tahap 10 and 20).

Writes the pgfplots files that the papers in paper/draft/ input, and prints the numbers behind them:
  gambar_rq2.tex        risk and coverage of the E2 conditions (skeleton fig:rq2)
  gambar_replay.tex     regulation replay per event for both chains (skeleton fig:replay)
  gambar_replay_en.tex  the same figure with English labels, for paper_en.tex

    env\\Scripts\\python system\\tools\\paper_figures.py
"""
import csv
import sys
from collections import Counter
from pathlib import Path

REPO = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(REPO / "system"))

from pph21kbs.analysis.stats import clopper_pearson  # noqa: E402

EXP = REPO / "experiments"
OUT = REPO / "paper" / "draft"
MAIN = ("e2-regulasi", "e2-pkb")

# table row of the paper: label, runs, condition in scores.csv
CONDITIONS = [
    ("Usulan", MAIN, "proposed"),
    ("B3", MAIN, "B3"),
    ("B4", MAIN, "B4"),
    ("AB2", ("e2-ab2-regulasi", "e2-ab2-pkb"), "proposed"),
    ("AB3 tanpa G5", MAIN, "AB3_noG5"),
    ("AB3 tanpa G4", MAIN, "AB3_noG4"),
    ("AB3 tanpa perbaikan", MAIN, "AB3_norepair"),
    ("AB4 pertama lolos", MAIN, "AB4_first"),
    ("AB4 seleksi sempurna", MAIN, "AB4_perfect"),
    ("$m = 5$", ("e2-regulasi-m5", "e2-pkb-m5"), "proposed"),
    ("Model kedua", ("e2-model2-regulasi", "e2-model2-pkb"), "proposed"),
    ("Model kedua B3", ("e2-model2-regulasi", "e2-model2-pkb"), "B3"),
]
# where the label of a point goes, as (anchor, x shift, y shift); points that coincide share one label
PLACE = {
    (11, 3): ("north east", -3, -3),
    (15, 7): ("north west", 3, -3),
    (12, 3): ("west", 4, -5),
    (11, 5): ("east", -3, 4),
    (10, 3): ("south east", -3, 2),
    (16, 8): ("south east", 28, 6),
    (8, 0): ("south west", 3, 1),
    (13, 7): ("south east", -2, 10),
}
# long labels break after this many conditions
BREAK = {(11, 3): 2, (10, 3): 1}
# one replay figure per language of the paper, from the same data
REPLAY_TEXT = (
    {"file": "gambar_replay.tex", "ylabel": "Kasus salah",
     "series": ("Kesalahan bawaan", "Kesalahan baru", "Kesalahan terpicu"),
     "chains": ("Rantai transplantasi", "Rantai pembangkitan ulang")},
    {"file": "gambar_replay_en.tex", "ylabel": "Wrong cases",
     "series": ("Inherited errors", "New errors", "Triggered errors"),
     "chains": ("Transplantation chain", "Regeneration chain")},
)


def real_outcomes(runs, condition):
    """Outcome per real document for one condition; only the 18 documents of the main runs count."""
    keep = set()
    for run in MAIN:
        with open(EXP / run / "scores.csv", encoding="utf-8") as f:
            keep |= {r["event"] for r in csv.DictReader(f)}
    out = {}
    for run in runs:
        with open(EXP / run / "scores.csv", encoding="utf-8") as f:
            for r in csv.DictReader(f):
                if r["condition"] == condition and r["event"] in keep:
                    out[r["event"]] = r["outcome"]
    return out


def conditions():
    rows = []
    for label, runs, condition in CONDITIONS:
        n = Counter(real_outcomes(runs, condition).values())
        wrong, right, total = n["salah"], n["benar"], sum(n.values())
        rows.append((label, wrong, right, total))
    return rows


def rq2_points(rows):
    """Conditions that land on the same coverage and risk share one point and one label."""
    points = {}
    for label, wrong, right, total in rows:
        points.setdefault((wrong + right, wrong, total), []).append(label)
    return points


def figure_rq2(rows):
    lines = [
        r"% Generated by system/tools/paper_figures.py from experiments/e2-*/scores.csv; do not edit.",
        r"\definecolor{usulan}{HTML}{2A78D6}",
        r"\begin{tikzpicture}",
        r"\begin{axis}[width=\columnwidth, height=7.2cm, scale only axis=false, xmin=0.2, xmax=1, ymin=0, ymax=0.85,",
        r"  xlabel={Cakupan (proporsi dokumen yang diterapkan)},",
        r"  ylabel={Risiko selektif (proporsi salah)},",
        r"  label style={font=\footnotesize}, tick label style={font=\footnotesize},",
        r"  xtick={0.2,0.4,0.6,0.8,1}, ytick={0,0.2,0.4,0.6,0.8},",
        r"  xticklabel style={/pgf/number format/.cd, fixed, fixed zerofill, precision=1, use comma},",
        r"  yticklabel style={/pgf/number format/.cd, fixed, fixed zerofill, precision=1, use comma},",
        r"  ymajorgrids, grid style={gray!20, line width=0.3pt}, axis lines*=left, tick style={draw=none},",
        r"  legend style={font=\footnotesize, draw=none, fill=none, at={(0,1.02)}, anchor=south west,",
        r"    legend columns=2, /tikz/every even column/.append style={column sep=6pt}}]",
    ]
    groups = {False: [], True: []}
    nodes = []
    for (covered, wrong, total), labels in rq2_points(rows).items():
        x, y = covered / total, wrong / covered
        xlo, xhi = clopper_pearson(covered, total)
        ylo, yhi = clopper_pearson(wrong, covered)
        print(f"  coverage {covered}/{total}={x:.3f} [{xlo:.3f}, {xhi:.3f}], "
              f"risk {wrong}/{covered}={y:.3f} [{ylo:.3f}, {yhi:.3f}]: {', '.join(labels)}")
        groups["Usulan" in labels].append(
            f"({x:.4f},{y:.4f}) += ({xhi - x:.4f},{yhi - y:.4f}) -= ({x - xlo:.4f},{y - ylo:.4f})")
        anchor, dx, dy = PLACE[(covered, wrong)]
        cut = BREAK.get((covered, wrong), len(labels))
        text = ", ".join(labels[:cut]) + (r",\\" + ", ".join(labels[cut:]) if labels[cut:] else "")
        nodes.append(rf"\node[font=\footnotesize, anchor={anchor}, inner sep=1pt, fill=white, fill opacity=0.8, "
                     rf"text opacity=1, xshift={dx}pt, yshift={dy}pt, align=right] at (axis cs:{x:.4f},{y:.4f}) "
                     rf"{{{text}}};")
    for highlight, name, colour, mark, size, whisker in ((False, "Kondisi lain", "black!55", "o", 1.7, 0.45),
                                                         (True, "Usulan", "usulan", "*", 2.2, 0.9)):
        lines += [
            rf"\addplot[only marks, mark={mark}, mark size={size}pt, draw={colour}, fill={colour},",
            r"  error bars/.cd, x dir=both, x explicit, y dir=both, y explicit,",
            rf"  error bar style={{draw={colour}, line width=0.35pt, opacity={whisker}}}, error mark=none]",
            "  coordinates {" + "\n    ".join(groups[highlight]) + "};",
            rf"\addlegendentry{{{name}}}",
        ]
    lines += nodes + [r"\end{axis}", r"\end{tikzpicture}", ""]
    (OUT / "gambar_rq2.tex").write_text("\n".join(lines), encoding="utf-8", newline="\n")


def read_chain(run):
    with open(EXP / run / "chain.csv", encoding="utf-8") as f:
        return list(csv.DictReader(f))


def event_types():
    with open(REPO / "dataset" / "09_korpus_peristiwa" / "peristiwa.csv", encoding="utf-8") as f:
        return {r["id"]: r["jenis_perubahan"].replace(" ", "") for r in csv.DictReader(f)}


def stack(row):
    """Bars that sum to the wrong cases of the event: inherited, new but not triggered, triggered."""
    wrong, new, triggered = int(row["wrong"]), int(row["new_errors"]), int(row["triggered"] or 0)
    return wrong - new, new - triggered, triggered


def panel(rows, title, ymax, ticks, labels, last, text):
    n = len(rows)
    series = [("gray!40", text["series"][0], 0), ("usulan", text["series"][1], 1), ("terpicu", text["series"][2], 2)]
    lines = [
        r"\begin{axis}[" + ("name=bawah, at={(atas.south west)}, anchor=north west, yshift=-6mm," if last else "name=atas,"),
        r"  ybar stacked, bar width=4pt, scale only axis, width=0.93\textwidth, height=\replaytinggi,",
        rf"  xmin=0.2, xmax={n + 0.8}, ymin=0, ymax={ymax}, ytick={{{ticks}}},",
        rf"  xtick={{1,...,{n}}}, xticklabels={{{','.join(labels) if last else ''}}},",
        r"  xticklabel style={rotate=90, anchor=east, font=\footnotesize, inner sep=1pt}," if last else r"  xtick style={draw=none},",
        rf"  ylabel={{{text['ylabel']}}}, label style={{font=\footnotesize}}, tick label style={{font=\footnotesize}},",
        r"  ymajorgrids, grid style={gray!20, line width=0.3pt}, axis lines*=left, tick style={draw=none},",
        rf"  title={{{title}}}, title style={{font=\footnotesize, at={{(0,1)}}, anchor=south west, yshift=-1pt}},",
        (r"  legend style={font=\footnotesize, draw=none, fill=none, at={(1,1.02)}, anchor=south east, legend columns=3,"
         r" /tikz/every even column/.append style={column sep=6pt}}, reverse legend=false," if not last else r"  legend style={draw=none},"),
        r"]",
    ]
    for colour, name, i in series:
        points = " ".join(f"({k},{stack(r)[i]})" for k, r in enumerate(rows, start=1))
        lines.append(rf"\addplot[fill={colour}, draw=none] coordinates {{{points}}};")
        if not last:
            lines.append(rf"\addlegendentry{{{name}}}")
    for k, r in enumerate(rows, start=1):
        if r["abstain"] == "True":
            lines.append(rf"\node[font=\footnotesize, anchor=south, inner sep=1pt] at (axis cs:{k},{sum(stack(r))}) {{A}};")
    lines.append(r"\end{axis}")
    return lines


def figure_replay():
    chains = (("e3-tetap", 640, "0,200,400,600"), ("e3-bangkit-ulang", 120, "0,40,80,120"))
    data = [read_chain(run) for run, *_ in chains]
    assert [r["event"] for r in data[0]] == [r["event"] for r in data[1]], "both chains must use the same order"
    types = event_types()
    labels = [f"{r['event']} {types.get(r['event'], '').split(';')[0]}".strip().replace(",", "/") for r in data[0]]
    for (run, *_), rows in zip(chains, data):
        print(f"  {run}: wrong at end {rows[-1]['wrong']} of {rows[-1]['cases']}; "
              f"new {sum(int(r['new_errors']) for r in rows)}; triggered {sum(int(r['triggered'] or 0) for r in rows)}; "
              f"abstain {sum(r['abstain'] == 'True' for r in rows)}")
    for text in REPLAY_TEXT:
        lines = [
            r"% Generated by system/tools/paper_figures.py from experiments/e3-*/chain.csv; do not edit.",
            r"\providecommand{\replaytinggi}{2.5cm}",
            r"\definecolor{usulan}{HTML}{2A78D6}",
            r"\definecolor{terpicu}{HTML}{EB6834}",
            r"\begin{tikzpicture}",
        ]
        for i, ((_, ymax, ticks), rows, title) in enumerate(zip(chains, data, text["chains"])):
            lines += panel(rows, title, ymax, ticks, labels, i == 1, text)
        lines += [r"\end{tikzpicture}", ""]
        (OUT / text["file"]).write_text("\n".join(lines), encoding="utf-8", newline="\n")


def main():
    rows = conditions()
    print("E2 conditions (wrong, right, documents):")
    for row in rows:
        print("  ", row)
    print("rq2 points:")
    figure_rq2(rows)
    print("replay:")
    figure_replay()
    print("written:", "gambar_rq2.tex", *[text["file"] for text in REPLAY_TEXT], "in", OUT)


if __name__ == "__main__":
    main()
